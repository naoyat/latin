_CRASIS_KEYS = {orthography.key(k): v for k, v in CRASIS.items()}


def split_crasis(word):
    """融合した語なら元の2語、でなければ None"""
    key = orthography.key(word)
    return _CRASIS_KEYS.get(key) or _CRASIS_KEYS.get(key.lower())
